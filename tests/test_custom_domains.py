class TestDomainValidationLogic(unittest.TestCase):
    def setUp(self):
        self.fqdn_regex = re.compile(
            r"^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9][a-z0-9-]{0,61}[a-z0-9]$"
        )

    def is_valid_hostname(self, val: str) -> bool:
        val = val.lower().strip()
        if "://" in val or "/" in val or ":" in val or " " in val:
            return False
        if len(val) < 3 or len(val) > 253:
            return False
        return bool(self.fqdn_regex.match(val))

    def test_valid_hostnames(self):
        valid = [
            "example.com",
            "app.vexlyx.com",
            "sub.domain.co.uk",
            "my-cool-app.io",
            "api-v2.staging.internal.net",
        ]
        for host in valid:
            self.assertTrue(self.is_valid_hostname(host), f"Should be valid: {host}")

    def test_invalid_hostnames(self):
        invalid = [
            "https://example.com",
            "http://app.com",
            "example.com:8080",
            "example.com/path",
            "-leading-dash.com",
            "trailing-dash-.com",
            "spaces in domain.com",
            "justwords",
            ".dotstart.com",
            "dotend.com.",
        ]
        for host in invalid:
            self.assertFalse(self.is_valid_hostname(host), f"Should be invalid: {host}")


class TestTraefikDynamicRouterLogic(unittest.TestCase):
    def test_traefik_yaml_generation(self):
        domain_id = "test-domain-123"
        hostname = "app.example.com"
        project_id = "clxyz987654321"
        service_name = re.sub(r"[^a-z0-9-]", "-", project_id[:12].lower()).strip("-")

        expected_yaml = f"""# Auto-generated by Vexlyx for domain: {hostname}
# Project: My Project ({project_id})
http:
  routers:
    domain-{domain_id}:
      rule: Host(`{hostname}`)
      entryPoints:
        - web
      service: {service_name}@docker
"""
        self.assertIn(f"rule: Host(`{hostname}`)", expected_yaml)
        self.assertIn(f"service: {service_name}@docker", expected_yaml)
        self.assertIn("entryPoints:\n        - web", expected_yaml)


class TestDnsTxtVerificationLogic(unittest.TestCase):
    def test_verification_match(self):
        token = "vexlyx-verify-a1b2c3d4e5f67890"
        expected_value = f"vexlyx-verification={token}"

        # Case 1: exact match in records
        records = [f"vexlyx-verification={token}", "google-site-verification=xyz"]
        matched = any(expected_value in r for r in records)
        self.assertTrue(matched)

        # Case 2: no match
        bad_records = ["v=spf1 include:_spf.google.com ~all"]
        matched = any(expected_value in r for r in bad_records)
        self.assertFalse(matched)


