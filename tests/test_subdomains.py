FQDN_REGEX = re.compile(
    r"^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9][a-z0-9-]{0,61}[a-z0-9]$"
)

SECOND_LEVEL_TLDS = ["co.uk", "com.au", "co.nz", "co.jp", "com.br", "org.uk", "gov.uk"]


def is_valid_hostname(val: str) -> bool:
    val = val.lower().strip()
    if "://" in val or "/" in val or ":" in val or " " in val:
        return False
    if len(val) < 3 or len(val) > 253:
        return False

    if val.startswith("*."):
        remaining = val[2:]
        if "." not in remaining or "*" in remaining:
            return False
        return bool(FQDN_REGEX.match(remaining))

    return bool(FQDN_REGEX.match(val))


def is_wildcard_hostname(hostname: str) -> bool:
    return hostname.startswith("*.")


def get_parent_domain(hostname: str) -> str | None:
    clean = hostname.lower().strip()
    is_wild = clean.startswith("*.")
    stripped = clean[2:] if is_wild else clean
    parts = stripped.split(".")

    if len(parts) <= 2:
        if is_wild and len(parts) == 2:
            return stripped
        return None

    last_two = ".".join(parts[-2:])
    if last_two in SECOND_LEVEL_TLDS:
        if len(parts) > 3:
            return ".".join(parts[1:])
        return stripped if is_wild else None

    return ".".join(parts[1:])


def is_subdomain(hostname: str) -> bool:
    if is_wildcard_hostname(hostname):
        return True
    return get_parent_domain(hostname) is not None


def generate_traefik_router_yaml(
    domain_id: str,
    hostname: str,
    project_id: str,
    project_name: str,
    port: int = 3000,
    path_prefix: str | None = None,
) -> str:
    service_name = re.sub(r"[^a-z0-9-]", "-", project_id[:12].lower()).strip("-")
    is_wildcard = is_wildcard_hostname(hostname)
    priority = 10 if is_wildcard else 100

    rule = f"Host(`{hostname}`)"
    if path_prefix and path_prefix.strip():
        rule = f"Host(`{hostname}`) && PathPrefix(`{path_prefix.strip()}`)"

    return f"""# Auto-generated by Vexlyx for domain: {hostname}
# Project: {project_name} ({project_id})
http:
  routers:
    domain-{domain_id}:
      rule: {rule}
      priority: {priority}
      entryPoints:
        - web
      service: service-{domain_id}
  services:
    service-{domain_id}:
      loadBalancer:
        servers:
          - url: "http://vexlyx-{service_name}-app-1:{port}"
"""


