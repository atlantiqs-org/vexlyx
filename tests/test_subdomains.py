class TestSubdomainHostnameValidation(unittest.TestCase):
    def test_acceptance_criteria_subdomains(self):
        """Acceptance criteria: api.domain.com, blog.domain.com, app.domain.com, *.domain.com"""
        criteria_domains = [
            "api.domain.com",
            "blog.domain.com",
            "app.domain.com",
            "*.domain.com",
        ]
        for host in criteria_domains:
            self.assertTrue(is_valid_hostname(host), f"Should be valid: {host}")

    def test_additional_valid_subdomains_and_wildcards(self):
        valid = [
            "staging.app.domain.com",
            "*.staging.example.com",
            "sub.my-site.co.uk",
            "*.my-site.co.uk",
            "v1-api.service.internal.io",
        ]
        for host in valid:
            self.assertTrue(is_valid_hostname(host), f"Should be valid: {host}")

    def test_invalid_wildcards_and_subdomains(self):
        invalid = [
            "*.com",               # TLD wildcard not allowed
            "*domain.com",         # Missing dot after asterisk
            "*.*.domain.com",      # Double wildcard
            "api.*.domain.com",    # Mid-label wildcard
            "*",                   # Lone asterisk
            "*.",                  # Asterisk with lone dot
            "http://api.domain.com",
            "api.domain.com/path",
            "api.domain.com:3000",
            "api domain.com",
        ]
        for host in invalid:
            self.assertFalse(is_valid_hostname(host), f"Should be invalid: {host}")


class TestSubdomainHelpers(unittest.TestCase):
    def test_is_wildcard(self):
        self.assertTrue(is_wildcard_hostname("*.domain.com"))
        self.assertTrue(is_wildcard_hostname("*.app.domain.com"))
        self.assertFalse(is_wildcard_hostname("api.domain.com"))
        self.assertFalse(is_wildcard_hostname("domain.com"))

    def test_get_parent_domain(self):
        self.assertEqual(get_parent_domain("api.domain.com"), "domain.com")
        self.assertEqual(get_parent_domain("blog.domain.com"), "domain.com")
        self.assertEqual(get_parent_domain("*.domain.com"), "domain.com")
        self.assertEqual(get_parent_domain("staging.api.domain.com"), "api.domain.com")
        self.assertIsNone(get_parent_domain("domain.com"))
        self.assertIsNone(get_parent_domain("example.co.uk"))
        self.assertEqual(get_parent_domain("api.example.co.uk"), "example.co.uk")
        self.assertEqual(get_parent_domain("*.example.co.uk"), "example.co.uk")

    def test_is_subdomain(self):
        self.assertTrue(is_subdomain("api.domain.com"))
        self.assertTrue(is_subdomain("*.domain.com"))
        self.assertTrue(is_subdomain("api.example.co.uk"))
        self.assertFalse(is_subdomain("domain.com"))
        self.assertFalse(is_subdomain("example.co.uk"))


class TestTraefikRouterPrioritiesAndRules(unittest.TestCase):
    def test_specific_subdomain_priority(self):
        yaml = generate_traefik_router_yaml(
            domain_id="dom-api-1",
            hostname="api.domain.com",
            project_id="cmprojectapi001",
            project_name="API Project",
            port=8000,
        )
        self.assertIn("rule: Host(`api.domain.com`)", yaml)
        self.assertIn("priority: 100", yaml)
        self.assertIn("http://vexlyx-cmprojectapi-app-1:8000", yaml)

    def test_wildcard_subdomain_priority(self):
        yaml = generate_traefik_router_yaml(
            domain_id="dom-wild-1",
            hostname="*.domain.com",
            project_id="cmprojectmain01",
            project_name="Main App",
            port=3000,
        )
        self.assertIn("rule: Host(`*.domain.com`)", yaml)
        self.assertIn("priority: 10", yaml)  # Lower priority than specific subdomain
        self.assertIn("http://vexlyx-cmprojectmai-app-1:3000", yaml)


    def test_path_prefix_routing(self):
        yaml = generate_traefik_router_yaml(
            domain_id="dom-path-1",
            hostname="domain.com",
            project_id="cmprojectapi001",
            project_name="API Project",
            port=8000,
            path_prefix="/api",
        )
        self.assertIn("rule: Host(`domain.com`) && PathPrefix(`/api`)", yaml)
        self.assertIn("priority: 100", yaml)


class TestVerificationInheritanceLogic(unittest.TestCase):
    def test_account_level_inheritance(self):
        parent_domain = {
            "id": "dom_parent_1",
            "hostname": "domain.com",
            "status": "ACTIVE",
            "verificationToken": "vexlyx-verify-abcdef1234567890",
        }

        # Creating child subdomain when parent is ACTIVE
        is_parent_active = parent_domain["status"] == "ACTIVE"
        subdomain_status = "ACTIVE" if is_parent_active else "PENDING"
        self.assertEqual(subdomain_status, "ACTIVE")

    def test_pending_parent_requires_challenge(self):
        parent_domain = {
            "id": "dom_parent_2",
            "hostname": "newdomain.com",
            "status": "PENDING",
        }
        is_parent_active = parent_domain["status"] == "ACTIVE"
        subdomain_status = "ACTIVE" if is_parent_active else "PENDING"
        self.assertEqual(subdomain_status, "PENDING")

    def test_wildcard_verification_target(self):
        wildcard_host = "*.domain.com"
        base_target = wildcard_host[2:] if wildcard_host.startswith("*.") else wildcard_host
        expected_record_name = f"_vexlyx-challenge.{base_target}"
        self.assertEqual(expected_record_name, "_vexlyx-challenge.domain.com")


